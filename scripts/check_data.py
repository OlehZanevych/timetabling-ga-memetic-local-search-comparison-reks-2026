#!/usr/bin/env python3
"""Check that data/ holds exactly the instances the experiments use, byte for byte.

The experiments generate their instances in memory from (size, seed); data/ ships the same instances
in the plain-text format so that a solver sharing no code with this one can use them.  This script
regenerates every instance with `experiments instances` into a temporary directory and compares each
file with the gzipped copy in data/, and checks data/MANIFEST.tsv (SHA-256 of every uncompressed
file).  With --write-manifest it (re)writes the manifest instead of checking it.

    python3 scripts/check_data.py [--binary build/experiments] [--write-manifest]

Standard library only.  Exits non-zero on any missing, extra or differing file.
"""
import argparse
import gzip
import hashlib
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def used_by(n, seed):
    """Which experiments of the article generate this (size, seed) pair."""
    u = []
    if seed >= 101:
        return "tune"
    if n == 6400:
        return "evalcost"
    if seed <= 10:
        u.append("compare")
    if n in (400, 1600):
        u.append("agreement" if seed > 10 else "agreement,budgetmode")
    if seed <= 6 and n in (400, 1600):
        u.append("crossover")
    if seed <= 6:
        u.append("evalcost")
    if seed <= 10 and n == 800:
        u.append("converge")
    if seed <= 10 and n in (800, 1600, 3200):
        u.append("timed")
    return ",".join(u) if u else "spare"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--binary", default=os.path.join(ROOT, "build", "experiments"))
    ap.add_argument("--write-manifest", action="store_true")
    args = ap.parse_args()
    data = os.path.join(ROOT, "data")
    if not os.access(args.binary, os.X_OK):
        sys.exit(f"build the application first: {args.binary} not found")

    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([args.binary, "instances", "--data", tmp], check=True,
                       stdout=subprocess.DEVNULL)
        generated = sorted(os.listdir(tmp))
        shipped = sorted(f[:-3] for f in os.listdir(data) if f.endswith(".txt.gz"))
        problems = []
        missing = sorted(set(generated) - set(shipped))
        extra = sorted(set(shipped) - set(generated))
        problems += [f"missing from data/: {m}.gz" for m in missing]
        problems += [f"not generated by any experiment: data/{e}.gz" for e in extra]
        rows = []
        for name in generated:
            with open(os.path.join(tmp, name), "rb") as fh:
                want = fh.read()
            digest = hashlib.sha256(want).hexdigest()
            if name in shipped:
                with gzip.open(os.path.join(data, name + ".gz"), "rb") as fh:
                    got = fh.read()
                if got != want:
                    problems.append(f"differs from the generator: data/{name}.gz")
            m = re.match(r"n(\d+)-s(\d+)(\.planted)?\.txt$", name)
            n, seed = int(m.group(1)), int(m.group(2))
            kind = "schedule" if m.group(3) else "instance"
            rows.append(f"{name}.gz\t{n}\t{seed}\t{kind}\t{used_by(n, seed)}\t{digest}")

    manifest = os.path.join(data, "MANIFEST.tsv")
    text = "file\tn\tseed\tkind\tused_by\tsha256_uncompressed\n" + "\n".join(rows) + "\n"
    if args.write_manifest:
        with open(manifest, "w") as fh:
            fh.write(text)
        print(f"wrote {manifest} ({len(rows)} files)")
    else:
        if not os.path.exists(manifest):
            problems.append("data/MANIFEST.tsv is missing (run with --write-manifest)")
        else:
            with open(manifest) as fh:
                if fh.read() != text:
                    problems.append("data/MANIFEST.tsv does not match the generated instances")

    for p in problems:
        print("  FAIL", p)
    if problems:
        print(f"{len(problems)} problem(s)")
        return 1
    print(f"data/ check passed: {len(rows)} files, each identical to the generator's output")
    return 0


if __name__ == "__main__":
    sys.exit(main())
